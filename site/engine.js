// SVG line chart of NAV paths. series: [{navs, c, id, dash?, w?}]
function drawChart(el, series, opts={}){
  const hasLabels = series.some(s => s.label);
  const W = opts.w||760, H = opts.h||340, m = {l:40, r:hasLabels?225:14, t:12, b:26};
  let lo = Infinity, hi = -Infinity;
  series.forEach(s => s.navs.forEach(v => { lo=Math.min(lo,v); hi=Math.max(hi,v); }));
  lo = Math.floor((lo-3)/10)*10; hi = Math.ceil((hi+3)/10)*10;
  const x = i => m.l + i/(NDAYS-1)*(W-m.l-m.r);
  const y = v => m.t + (hi-v)/(hi-lo)*(H-m.t-m.b);
  let g = `<svg viewBox="0 0 ${W} ${H}" style="display:block;width:100%;height:auto">`;
  for(let v = lo; v <= hi; v += (hi-lo>80?20:10)){
    g += `<line x1="${m.l}" x2="${W-m.r}" y1="${y(v)}" y2="${y(v)}" stroke="#e5d9b8" stroke-width="1.5"/>`;
    g += `<text x="${m.l-6}" y="${y(v)+4}" text-anchor="end" font-family="Space Mono" font-size="10" fill="#6b5f42">${v-100>0?'+':''}${v-100}%</text>`;
  }
  const MMM=["Jan","Feb","Mar","Apr","May","Jun","Jul","Aug","Sep","Oct","Nov","Dec"];
  const fmtDate=d=>MMM[+d.slice(5,7)-1]+"-"+d.slice(2,4);
  [0, Math.floor(NDAYS/2), NDAYS-1].forEach(i => {
    g += `<text x="${x(i)}" y="${H-6}" text-anchor="${i===0?'start':i===NDAYS-1?'end':'middle'}" font-family="Space Mono" font-size="10" fill="#6b5f42">${fmtDate(MARKET.dates[i])}</text>`;
  });
  g += `<line x1="${m.l}" x2="${W-m.r}" y1="${y(100)}" y2="${y(100)}" stroke="#20180a" stroke-width="1.6" opacity=".45"/>`;
  series.forEach(s => {
    const pts = s.navs.map((v,i) => `${x(i*(NDAYS-1)/(s.navs.length-1)).toFixed(1)},${y(v).toFixed(1)}`).join(" ");
    g += `<polyline id="${s.id||''}" points="${pts}" fill="none" stroke="${s.c}" stroke-width="${s.w||2.5}" ${s.dash?'stroke-dasharray="6 5"':''} stroke-linejoin="round" stroke-linecap="round"/>`;
  });
  if(hasLabels){
    // end-of-line labels, nudged apart so they never overlap
    const labs = series.filter(s => s.label)
      .map(s => ({s, ly: y(s.navs[s.navs.length-1])}))
      .sort((a,b) => a.ly - b.ly);
    for(let i = 1; i < labs.length; i++)
      if(labs[i].ly - labs[i-1].ly < 14) labs[i].ly = labs[i-1].ly + 14;
    labs.forEach(({s, ly}) => {
      g += `<text id="${s.id?s.id+'-lab':''}" x="${W-m.r+8}" y="${ly+4}" font-family="Space Mono" font-size="10.5" font-weight="700" fill="${s.c}">${s.label}</text>`;
    });
  }
  g += `</svg>`;
  el.innerHTML = g;
}

